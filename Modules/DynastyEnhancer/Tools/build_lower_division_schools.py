"""Generate a bounded native football-school catalog; no network at build time."""
import json
from pathlib import Path

root=Path(__file__).resolve().parents[1]
data=json.loads((root/'Config/lower-division-schools.json').read_text(encoding='utf8'))
schools=data['schools']
assert len(schools)>=450
assert len({(s['level'],s['name'],s['state']) for s in schools})==len(schools)
quote=lambda v:json.dumps(v,ensure_ascii=True)
lines=['// Generated by Tools/build_lower_division_schools.py. Factual names from Config catalog.',
       '#pragma once','namespace recruitingfog::resume {',
       'struct CollegeSchool {const char* level;const char* name;const char* institution;const char* city;const char* state;};',
       'inline constexpr CollegeSchool collegeSchools[]={']
for s in schools:lines.append('    {'+','.join(quote(s[k]) for k in ('level','name','institution','city','state'))+'},')
lines+=['};','}']
(root/'Source/RecruitCollegeSchools.h').write_text('\n'.join(lines)+'\n',encoding='utf8')
print(f'Validated {len(schools)} current football programs.')
