import {observeOffseason} from './offseason_ledger.mjs';
import {offseasonLedgerFile,readOffseasonLedger} from './offseason_ledger_store.mjs';
import fs from 'node:fs/promises';
import path from 'node:path';
import {performance} from 'node:perf_hooks';
import {readRuntime} from './read_runtime.mjs';
import {updateRuntime,scopeKey} from './runtime_lifecycle.mjs';
import {readHistory,loadArchives,atomicJson,writeHistory} from './runtime_archive.mjs';
const [input,output]=process.argv.slice(2);
if(!input||!output)throw Error('Usage: node export_runtime.mjs runtime-raw.json output.json');
const started=performance.now(),timings={};let marked=started;
const mark=key=>{const now=performance.now();timings[key]=Math.round(now-marked);marked=now;};
const raw=JSON.parse(await fs.readFile(input,'utf8'));mark('inputMs');
const s=await readRuntime(raw);mark('normalizeMs');
const directory=path.join(path.dirname(input),'RuntimeHistory',scopeKey(s)),file=path.join(directory,'history.json');
const ledgerFile=offseasonLedgerFile(path.dirname(input),s);
const [state,archives,ledger]=await Promise.all([readHistory(file,{activeWeek:s.season.CurrentWeek}),loadArchives(path.dirname(input),s),readOffseasonLedger(ledgerFile)]);mark('historyReadMs');
const carry=observeOffseason(s,ledger,{history:[...archives,...(state?.editions??[]).map(e=>e.feed)]});s.offseasonCarry=carry.facts;
const result=updateRuntime(s,state??undefined,{archives});mark('generationMs');
await fs.mkdir(directory,{recursive:true});await atomicJson(ledgerFile,carry.ledger);await writeHistory(file,result.state);mark('historyWriteMs');
await atomicJson(output,result.catalog);mark('catalogWriteMs');
console.log(JSON.stringify({event:'runtime_feed_ready',league:s.leagueId,team:s.userTeamIndex,week:s.season.CurrentWeek,stories:result.catalog.stories.length,posts:result.catalog.posts.length,carryoverFacts:carry.facts.length,newOffers:s.newOffers.length,newCommitments:s.newCommitments.length,sha256:s.sha256,timings:{...timings,totalMs:Math.round(performance.now()-started)}}));
